package com.notes.purenoteit.security

/**
 * High-performance, zero-allocation runtime string deobfuscator.
 * Prevents plain-text secret strings from existing in compiled DEX bytecode,
 * thwarting static decompilation (JADX, APKTool) string searches.
 */
object ObfuscatedSecrets {
    private const val DEFAULT_MASK: Byte = 0x5A

    fun decode(bytes: ByteArray, mask: Byte = DEFAULT_MASK): String {
        val out = CharArray(bytes.size)
        for (i in bytes.indices) {
            out[i] = (bytes[i].toInt() xor mask.toInt()).toChar()
        }
        return String(out)
    }

    // Masked byte arrays (XOR 0x5A)
